// Builds styles/iconoir.css with only the icons the site uses, instead of
// the full iconoir sheet (~2.9 MB). Run `npm run icons` after changing ICONS.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// Icons used in code, plus icons written as `name` in Storyblok text and
// action labels (rendered by components/typography.tsx). An icon added in
// Storyblok shows up only once it is listed here.
export const ICONS = [
  // code
  'arrow-left',
  'arrow-right',
  'calendar',
  'calendar-arrow-down',
  'calendar-arrow-up',
  'check',
  'clock',
  'code',
  'group',
  'nav-arrow-down',
  'nav-arrow-up',
  'play-solid',
  'user',
  'whatsapp-solid',
  // person roles
  'design-nib',
  'graduation-cap',
  'light-bulb-on',
  'one-point-circle',
  'ruler-combine',
  'sphere',
  'tools',
  // Storyblok content
  'facebook',
  'instagram',
  'linkedin',
  'pinterest',
  'youtube',
]

const source = fileURLToPath(new URL('../node_modules/iconoir/css/iconoir.css', import.meta.url))
const target = fileURLToPath(new URL('../styles/iconoir.css', import.meta.url))

export function buildIconCss(css = readFileSync(source, 'utf8')) {
  // Icon rules sit on one long line after the shared base rules
  const base = css.slice(0, css.indexOf('.iconoir-'))
  const rules = new Map()
  for (const match of css.matchAll(/\.iconoir-([a-z0-9-]+)::before\{[^}]*\}/g)) {
    rules.set(match[1], match[0])
  }
  const missing = ICONS.filter((name) => !rules.has(name))
  if (missing.length) throw new Error(`Unknown iconoir icons: ${missing.join(', ')}`)
  return `${base.trimEnd()}\n/* Generated by scripts/icons.mjs, do not edit */\n${ICONS.map((name) => rules.get(name)).join('\n')}\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(target, buildIconCss())
  console.log(`styles/iconoir.css: ${ICONS.length} icons`)
}
